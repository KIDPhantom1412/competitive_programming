#include <algorithm>
#include <iostream>

using LL = long long;

// n 最大 1e5，k 最大 100
const int N = int(1e5) + 5, M = 105, MOD = int(1e9) + 7;

int n, m; // n 节点数，m 设备数 k
int H[N]; // 邻接表头指针，H[u] 表示从 u 出发的第一条边的编号
struct EdgeNode {
    int v, n; // v 是目标节点，n 是下一条边的编号
} E[N * 2];   // 无向树，每条边存两次，所以开 2 倍
int idx;      // 边的编号计数器

void add(int a, int b) {
    // 头插法建立邻接表：
    // 新边指向原来的第一条边，再把 H[a] 更新为新边的编号
    E[++idx] = {b, H[a]}, H[a] = idx;
}

int size[N]; // 以 u 为根的子树大小

// f[u][j][s][c] 状态定义：
//   u：当前节点
//   j：子树 u 中使用了 j 个设备
//   s = 0/1：u 是否放置设备（0 不放，1 放）
//   c = 0/1：u 是否被某个子节点覆盖（0 没被覆盖，1 已被覆盖）
int f[N][M][2][2];

void dfs(int u, int fa) {
    size[u] = 1;

    // ---------- 初始化叶子节点的两种基本状态 ----------
    // 状态 1：u 不选，u 也没被覆盖，0 个设备
    // 这个状态对非根节点是合法的，因为 u 可能被父节点覆盖
    f[u][0][0][0] = 1;
    // 状态 2：u 选，消耗 1 个设备，u 还没被自己的子节点覆盖
    // 注意：设备不能覆盖自己，所以 u 选了不代表 u 被覆盖
    f[u][1][1][0] = 1;

    // 遍历 u 的所有邻居
    for (int i = H[u]; i; i = E[i].n) {
        int v = E[i].v; // 注意这里取 v，不能取 n（n 是 next 指针）
        if (v != fa) {  // 只往子树方向走，避免回到父节点
            dfs(v, u);  // 先递归处理子节点

            size[u] += size[v]; // 合并子树大小

            // ---------- 树上背包：把子节点 v 合并到 u 中 ----------
            // j 必须倒序，避免同一子节点被重复选取（类似 0/1 背包）
            for (int j = std::min(m, size[u]); j >= 1; j--) {
                // 当 j 可以让子节点贡献 0 个设备时，先单独处理 k = 0
                // 否则 k 从 1 开始
                if (std::max(0, j - (size[u] - size[v])) == 0) {
                    // c, d 分别保存旧状态：
                    // c = u 选，u 还没被自己的子节点覆盖
                    // d = u 选，u 已经被某个子节点覆盖
                    int c = f[u][j][1][0], d = f[u][j][1][1];

                    // 当 u 不选时，子节点贡献 0 设备意味着：
                    // 子节点自己没选，子节点的子树也没有设备，
                    // 而 u 又不覆盖它（因为 u 没选）=> 该子节点非法
                    // 因此 u 不选的两个状态全部清 0，等待 k >= 1 的合法转移
                    f[u][j][0][0] = 0;
                    f[u][j][0][1] = 0;

                    // 当 u 选时，子节点 0 设备是合法的，因为 u 会覆盖它
                    // 子节点 0 设备的合法状态是 f[v][0][0][0]（没被自己的子节点覆盖）
                    // f[v][0][0][1] 永远是 0（0 设备不可能被自己的子节点覆盖）
                    int child0 = (f[v][0][0][0] + f[v][0][0][1]) % MOD;
                    f[u][j][1][0] = LL(c) * child0 % MOD;
                    f[u][j][1][1] = LL(d) * child0 % MOD;
                }

                // 处理 k >= 1 的情况
                // k 从 1 到 min(j, size[v])，并且保证 j - k 不超过 u 的其余子树大小
                for (int k = std::max(1, j - (size[u] - size[v])); k <= std::min(j, size[v]); k++) {
                    // ---------- u 不选（s = 0） ----------
                    // 此时 u 不覆盖子节点 v，所以 v 必须被自己的子节点覆盖
                    // 因此只能取 f[v][k][*][1]

                    // 子节点不选，u 仍然没被覆盖
                    f[u][j][0][0] =
                        (f[u][j][0][0] + LL(f[v][k][0][1]) * f[u][j - k][0][0] % MOD) % MOD;

                    // 子节点选，覆盖 u -> u 变为被覆盖
                    // 子节点不选，但 u 已经被之前的子节点覆盖
                    // 子节点选，u 也已经被之前的子节点覆盖
                    f[u][j][0][1] = (f[u][j][0][1] + LL(f[v][k][1][1]) * f[u][j - k][0][0] % MOD +
                                     LL(f[v][k][0][1]) * f[u][j - k][0][1] % MOD +
                                     LL(f[v][k][1][1]) * f[u][j - k][0][1] % MOD) %
                                    MOD;

                    // ---------- u 选（s = 1） ----------
                    // 此时 u 覆盖子节点 v，所以 v 不需要被自己的子节点覆盖
                    // 可以取 f[v][k][*][0] 和 f[v][k][*][1]

                    // 子节点不选，u 仍然没被自己的子节点覆盖
                    f[u][j][1][0] = (f[u][j][1][0] +
                                     LL(f[v][k][0][0] + f[v][k][0][1]) * f[u][j - k][1][0] % MOD) %
                                    MOD;

                    // 子节点选，覆盖 u -> u 变为被覆盖
                    // 子节点不选，但 u 已经被之前的子节点覆盖
                    // 子节点选，u 也已经被之前的子节点覆盖
                    f[u][j][1][1] = (f[u][j][1][1] +
                                     LL(f[v][k][1][0] + f[v][k][1][1]) * f[u][j - k][1][0] % MOD +
                                     LL(f[v][k][0][0] + f[v][k][0][1]) * f[u][j - k][1][1] % MOD +
                                     LL(f[v][k][1][0] + f[v][k][1][1]) * f[u][j - k][1][1] % MOD) %
                                    MOD;
                }
            }

            // 关键：如果 u 有子节点，且 u 不选，那么 0 个设备不可能覆盖这些子节点
            // 所以 u 不选、0 设备、没被覆盖的状态要清 0
            // 叶子节点没有走这个循环，f[u][0][0][0] 仍然为 1，表示叶子等待父节点覆盖
            f[u][0][0][0] = 0;
        }
    }
}

int main() {
    std::ios::sync_with_stdio(false);
    std::cin.tie(nullptr);

    std::cin >> n >> m;
    for (int i = 0; i < n - 1; i++) {
        int a, b;
        std::cin >> a >> b;
        add(a, b), add(b, a); // 无向边，双向添加
    }

    dfs(1, -1); // 以 1 为根进行树形 DP

    // 根节点没有父节点，必须被自己的子节点覆盖
    // s = 0：根不选，被某个子节点覆盖
    // s = 1：根选，且被某个子节点覆盖（根不能自己覆盖自己）
    // 两种状态取和，再取模
    std::cout << (f[1][m][0][1] + f[1][m][1][1]) % MOD << '\n';

    return 0;
}
